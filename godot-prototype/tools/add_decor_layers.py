def convert_raw_to_csv(raw_text, output_path):
    """Parse raw TMX CSV tile data and write as x,y,atlasX,atlasY format."""
    rows = [r.strip() for r in raw_text.strip().split('\n') if r.strip()]
    lines = []
    for y, row in enumerate(rows):
        for x, cell in enumerate(row.split(',')):
            tile_id = int(cell)
            if tile_id == 0:
                continue
            atlas_id = tile_id - 1  # TMX firstgid=1, atlas is 0-based
            atlas_x = atlas_id % TILESET_COLUMNS
            atlas_y = atlas_id // TILESET_COLUMNS
            lines.append(f"{x},{y},{atlas_x},{atlas_y}")

    with open(output_path, 'w') as f:
        f.write('\n'.join(lines))
    return len(lines)


def main():
    base = os.path.join(os.path.dirname(__file__), '..', 'assets', 'map_data')
    os.makedirs(base, exist_ok=True)

    for name, raw in [
        ('Decor1PLevel', DECOR1_P_LEVEL),
        ('Decor2overP', DECOR2_OVER_P),
        ('Decor3overP', DECOR3_OVER_P),
    ]:
        path = os.path.join(base, f'{name}.csv')
        count = convert_raw_to_csv(raw, path)
        print(f'  {name}: {count} tiles -> {path}')


if __name__ == '__main__':
    main()
